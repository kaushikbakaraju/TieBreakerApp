import React, { useState } from 'react';
import { X, Copy, Check, Download, FileCode, FileText } from 'lucide-react';
import { Decision } from '../types/decision';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  decision: Decision;
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  decision,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  // Generate markdown format
  const generateMarkdown = (): string => {
    const lines: string[] = [];

    lines.push(`# ${decision.title}`);
    lines.push(`\n**Executive Summary:** ${decision.summary}\n`);
    lines.push(`**Decision Classification:** ${decision.decisionType.classification} (Reversibility: ${decision.decisionType.reversibilityScore}/10)`);
    lines.push(`*${decision.decisionType.rationale}*\n`);

    lines.push(`## The Tiebreaker Ruling`);
    const recommended = decision.options.find((o) => o.id === decision.tiebreakerVerdict.recommendedOptionId) || decision.options[0];
    lines.push(`- **Recommended Choice:** ${recommended.name} (${recommended.tagline})`);
    lines.push(`- **Confidence:** ${decision.tiebreakerVerdict.confidence}`);
    lines.push(`- **Ruling:** ${decision.tiebreakerVerdict.ruling}`);
    lines.push(`- **Deciding Factor:** ${decision.tiebreakerVerdict.decidingFactor}`);
    lines.push(`- **The Piercing Question:** "${decision.tiebreakerVerdict.theOneQuestion}"\n`);

    lines.push(`### Conditional Rules`);
    decision.tiebreakerVerdict.conditionalRules.forEach((rule) => {
      lines.push(`- *${rule.condition}* → **${rule.recommendation}**`);
    });
    lines.push('');

    lines.push(`## Options & Pros / Cons Breakdown`);
    decision.options.forEach((opt) => {
      lines.push(`### ${opt.name}`);
      lines.push(`*${opt.tagline}*\n`);
      lines.push(`**Pros:**`);
      opt.pros.forEach((p) => {
        lines.push(`- [Weight ${p.weight}/5] ${p.text} (${p.category})`);
        if (p.explanation) lines.push(`  *${p.explanation}*`);
      });
      lines.push(`\n**Cons:**`);
      opt.cons.forEach((c) => {
        lines.push(`- [Severity ${c.weight}/5] ${c.text} (${c.category})`);
        if (c.mitigation) lines.push(`  *Mitigation: ${c.mitigation}*`);
      });
      lines.push('');
    });

    lines.push(`## Multi-Criteria Comparison Matrix`);
    lines.push(`| Criterion | Weight | ${decision.options.map((o) => o.name).join(' | ')} |`);
    lines.push(`| --- | --- | ${decision.options.map(() => '---').join(' | ')} |`);
    decision.comparisonMatrix.criteria.forEach((crit) => {
      const scoreRow = decision.comparisonMatrix.scores.find((s) => s.criteriaId === crit.id);
      const scores = decision.options.map((o) => {
        const sc = scoreRow?.optionScores[o.id];
        return sc ? `${sc.score}/10` : 'N/A';
      });
      lines.push(`| ${crit.name} | ${crit.weight}x | ${scores.join(' | ')} |`);
    });
    lines.push('');

    lines.push(`## SWOT Analysis Summary`);
    decision.options.forEach((opt) => {
      lines.push(`### ${opt.name} - SWOT`);
      lines.push(`**Strengths:**`);
      opt.swot.strengths.forEach((s) => lines.push(`- **${s.title}:** ${s.detail} (Action: ${s.action})`));
      lines.push(`**Weaknesses:**`);
      opt.swot.weaknesses.forEach((w) => lines.push(`- **${w.title}:** ${w.detail} (Action: ${w.action})`));
      lines.push(`**Opportunities:**`);
      opt.swot.opportunities.forEach((o) => lines.push(`- **${o.title}:** ${o.detail} (Action: ${o.action})`));
      lines.push(`**Threats:**`);
      opt.swot.threats.forEach((t) => lines.push(`- **${t.title}:** ${t.detail} (Action: ${t.action})`));
      lines.push('');
    });

    lines.push(`---\n*Generated by The Tiebreaker Decision Studio on ${new Date().toLocaleDateString()}*`);
    return lines.join('\n');
  };

  const markdownText = generateMarkdown();

  const handleCopyMarkdown = () => {
    navigator.clipboard.writeText(markdownText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadMarkdown = () => {
    const blob = new Blob([markdownText], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${decision.title.toLowerCase().replace(/[^a-z0-9]+/g, '_')}_tiebreaker.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const handleDownloadJSON = () => {
    const jsonStr = JSON.stringify(decision, null, 2);
    const blob = new Blob([jsonStr], { type: 'application/json;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${decision.title.toLowerCase().replace(/[^a-z0-9]+/g, '_')}_tiebreaker.json`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-sm overflow-y-auto">
      <div className="relative w-full max-w-2xl bg-slate-900 border border-slate-800 rounded-2xl shadow-2xl p-6 sm:p-8 my-8">
        <div className="flex items-start justify-between pb-4 border-b border-slate-800">
          <div>
            <h3 className="text-lg font-bold text-white tracking-tight">
              Export Decision Dossier
            </h3>
            <p className="text-xs text-slate-400 mt-0.5">
              Copy as comprehensive Markdown or download files for team review.
            </p>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 text-slate-400 hover:text-white rounded-lg hover:bg-slate-800 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Action row */}
        <div className="flex flex-wrap items-center gap-2 pt-4 pb-3">
          <button
            onClick={handleCopyMarkdown}
            className="flex items-center gap-1.5 px-3.5 py-2 text-xs font-semibold text-white bg-indigo-600 hover:bg-indigo-500 rounded-lg shadow-sm transition-all"
          >
            {copied ? <Check className="w-4 h-4 text-emerald-300" /> : <Copy className="w-4 h-4" />}
            <span>{copied ? 'Copied to Clipboard!' : 'Copy Markdown'}</span>
          </button>
          <button
            onClick={handleDownloadMarkdown}
            className="flex items-center gap-1.5 px-3.5 py-2 text-xs font-semibold text-slate-200 hover:text-white bg-slate-800 hover:bg-slate-700 rounded-lg transition-all"
          >
            <FileText className="w-4 h-4 text-slate-400" />
            <span>Download .MD</span>
          </button>
          <button
            onClick={handleDownloadJSON}
            className="flex items-center gap-1.5 px-3.5 py-2 text-xs font-semibold text-slate-200 hover:text-white bg-slate-800 hover:bg-slate-700 rounded-lg transition-all"
          >
            <FileCode className="w-4 h-4 text-slate-400" />
            <span>Download .JSON</span>
          </button>
        </div>

        {/* Code / Markdown preview */}
        <div className="mt-2">
          <label className="block text-xs font-medium text-slate-400 mb-1.5">
            Dossier Preview
          </label>
          <textarea
            readOnly
            value={markdownText}
            rows={12}
            className="w-full px-3.5 py-2.5 text-xs font-mono bg-slate-950 border border-slate-800 rounded-xl text-slate-300 leading-relaxed focus:outline-none select-all"
          />
        </div>

        <div className="flex justify-end pt-4 border-t border-slate-800 mt-4">
          <button
            onClick={onClose}
            className="px-4 py-2 text-xs font-medium text-slate-300 hover:text-white bg-slate-800 hover:bg-slate-700 rounded-lg"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};
